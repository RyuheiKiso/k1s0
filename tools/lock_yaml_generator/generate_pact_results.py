"""tools/lock_yaml_generator/generate_pact_results.py

# pact_results.lock.yaml 生成器。
# src/client/pact/ ディレクトリを確認し、
# Pact コントラクトテスト結果の宣言状態を lock artifact として生成する。
# pact/ が存在しない場合は 5 consumer のスケルトンを使用する（全て declared）。
"""

# 標準ライブラリのインポート
from __future__ import annotations

# datetime モジュール: generated_at タイムスタンプ生成に使用
import datetime
# Path: ファイルパス操作に使用
from pathlib import Path
# Any: 型ヒントに使用
from typing import Any

# BaseGenerator と REPO_ROOT をインポートする
from tools.lock_yaml_generator.base_generator import BaseGenerator, REPO_ROOT

# pact ディレクトリの想定パス
_PACT_DIR = REPO_ROOT / "src/client/pact"

# スケルトン用 5 consumer 定義（SDK 5 class に対応）
_SKELETON_CONSUMERS: list[str] = [
    # ブラウザ SPA consumer
    "browser_spa",
    # Tauri デスクトップ consumer
    "tauri",
    # .NET Framework consumer
    "dotnet_fw",
    # フル native consumer
    "full_native",
    # 薄い API クライアント consumer
    "thin_api",
]


class PactResultsGenerator(BaseGenerator):
    """pact_results.lock.yaml 生成器。"""

    # 出力ファイル名
    OUTPUT_NAME = "pact_results.lock.yaml"
    # 必須入力なし（フォールバックあり）
    REQUIRED_INPUTS: list[str] = []
    # スキーマ検証なし
    SCHEMA_PATH: Path | None = None
    # 出力先ディレクトリ
    DEFAULT_OUTPUT_DIR = "src/client/lock"

    def load_inputs(self, lock_dir: Path) -> dict[str, Any]:
        """src/client/pact/ ディレクトリを確認する。
        存在する場合はディレクトリ情報を返す。存在しない場合は空 dict を返す。
        """
        # pact ディレクトリが存在するか確認する
        if _PACT_DIR.exists() and _PACT_DIR.is_dir():
            # *.json ファイルを探して consumer 一覧を取得する
            pact_files = sorted(_PACT_DIR.glob("*.json"))
            # consumer 一覧を返す
            return {
                "pact_dir_exists": True,
                "pact_files": [f.stem for f in pact_files],
            }
        # ディレクトリが存在しない場合は空 dict を返す
        return {}

    def build_artifact(self, inputs: dict[str, Any]) -> dict[str, Any]:
        """Pact コントラクトテスト結果の宣言状態を表す artifact dict を返す。
        pact/ が存在しない場合は 5 consumer のスケルトンを使用する（全て declared）。
        """
        # 現在時刻を UTC で生成する
        generated_at = datetime.datetime.now(tz=datetime.timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%SZ"
        )

        # pact ファイルの一覧を取得する
        pact_files: list[str] = inputs.get("pact_files", [])

        # pact ファイルが存在する場合はその consumer を登録する
        if pact_files:
            # 各 pact ファイルを consumer エントリとして declared で登録する
            results = [
                {
                    # consumer: ファイル名（拡張子なし）を consumer 名として使用
                    "consumer": consumer,
                    # status: 物理 Pact 検証は Stage 5 で実施するため declared とする
                    "status":   "declared",
                }
                for consumer in pact_files
            ]
        else:
            # フォールバック: スケルトン 5 consumer を declared で登録する
            results = [
                {
                    # consumer: スケルトンの consumer 名を使用
                    "consumer": consumer,
                    # status: 物理 Pact 検証は Stage 5 で実施するため declared とする
                    "status":   "declared",
                }
                for consumer in _SKELETON_CONSUMERS
            ]

        # artifact dict を構築して返す
        return {
            # 自動生成ヘッダ（手書き禁止の明示）
            "_AUTO_GENERATED": (
                "DO NOT EDIT. Generated by"
                " tools/lock_yaml_generator/generate_pact_results.py"
            ),
            # 生成日時
            "generated_at": generated_at,
            # Pact コントラクトテスト結果一覧（全て declared）
            "results": results,
        }

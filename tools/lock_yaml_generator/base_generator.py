"""tools/lock_yaml_generator/base_generator.py

全 lock.yaml generator の共通抽象基底クラス。
各 generator はこれを継承して OUTPUT_NAME / REQUIRED_INPUTS / SCHEMA_PATH を宣言し、
load_inputs / build_artifact を実装する。
"""

from __future__ import annotations

import datetime
import hashlib
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    raise ImportError("PyYAML required: pip install PyYAML")

try:
    import jsonschema
except ImportError:
    raise ImportError("jsonschema required: pip install jsonschema")

# リポジトリルート（このファイルは tools/lock_yaml_generator/ 配下）
REPO_ROOT: Path = Path(__file__).resolve().parent.parent.parent

# AUTO_GENERATED ヘッダ文字列
_AUTO_GENERATED = "DO NOT EDIT. Generated by tools/lock_yaml_generator."

# 出力 lock 名（mtime 計算から除外するファイル名集合）
_OUTPUT_LOCK_NAMES = frozenset({
    "release_gate.lock.yaml",
    "release_gate.cosign_trigger.lock.yaml",
})


def dump_deterministic(data: dict[str, Any]) -> str:
    """key 順序固定の YAML dump（bit-for-bit reproducible）。

    sort_keys=False で挿入順を保持し、allow_unicode=True で日本語を ASCII エスケープしない。
    width=4096 でラップを防止する。
    """
    return yaml.safe_dump(
        data,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=4096,
    )


def get_max_mtime(lock_dir: Path, exclude: frozenset[str] = _OUTPUT_LOCK_NAMES) -> str:
    """lock_dir 内の入力 .lock.yaml の最大 mtime を ISO8601 で返す。

    出力ファイル（release_gate.lock.yaml 等）は除外して bit-for-bit reproducibility を保つ。
    ファイルが 1 件もない場合は 1970-01-01T00:00:00Z を返す。
    """
    mtimes = [
        p.stat().st_mtime
        for p in lock_dir.glob("*.lock.yaml")
        if p.name not in exclude
    ]
    if not mtimes:
        return "1970-01-01T00:00:00Z"
    ts = datetime.datetime.fromtimestamp(max(mtimes), tz=datetime.timezone.utc)
    return ts.strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_of_text(text: str) -> str:
    """テキストの SHA-256 ハッシュを "sha256:<hex>" 形式で返す。"""
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


class BaseGenerator(ABC):
    """全 lock.yaml generator の共通抽象基底クラス。

    サブクラスは以下を宣言して実装する:
      OUTPUT_NAME: str          — 出力 lock.yaml ファイル名
      REQUIRED_INPUTS: list[str] — 依存する入力 lock.yaml 名のリスト
      SCHEMA_PATH: Path | None  — jsonschema ファイルへのパス（None = 検証スキップ）

    次の 2 つのメソッドを実装する:
      load_inputs(lock_dir)     — 入力データを読み込んで dict で返す
      build_artifact(inputs)    — artifact dict を構築して返す
    """

    OUTPUT_NAME: str
    REQUIRED_INPUTS: list[str] = []
    SCHEMA_PATH: Path | None = None

    @abstractmethod
    def load_inputs(self, lock_dir: Path) -> dict[str, Any]:
        """入力 lock.yaml や手書き YAML を読み込んで dict を返す。"""

    @abstractmethod
    def build_artifact(self, inputs: dict[str, Any]) -> dict[str, Any]:
        """artifact dict を構築して返す。_AUTO_GENERATED キーを含むこと。"""

    def validate_schema(self, artifact: dict[str, Any]) -> None:
        """jsonschema で artifact を検証する。SCHEMA_PATH が None の場合はスキップ。"""
        if self.SCHEMA_PATH is None:
            return
        if not self.SCHEMA_PATH.exists():
            return
        schema_text = self.SCHEMA_PATH.read_text(encoding="utf-8")
        schema = yaml.safe_load(schema_text)
        jsonschema.validate(instance=artifact, schema=schema)

    def dump_deterministic(self, artifact: dict[str, Any]) -> str:
        """key 順序固定の YAML dump。共通実装を委譲。"""
        return dump_deterministic(artifact)

    def emit(self, output_dir: Path) -> Path:
        """artifact を生成して output_dir / OUTPUT_NAME に書き出す。

        生成フロー:
          1. load_inputs(output_dir) で入力読み込み
          2. build_artifact(inputs) で artifact 構築
          3. validate_schema(artifact) で jsonschema 検証
          4. dump_deterministic(artifact) で YAML テキスト変換
          5. output_dir / OUTPUT_NAME に書き出す
          6. 書き出したパスを返す
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        inputs = self.load_inputs(output_dir)
        artifact = self.build_artifact(inputs)
        self.validate_schema(artifact)
        content = self.dump_deterministic(artifact)
        output_path = output_dir / self.OUTPUT_NAME
        output_path.write_text(content, encoding="utf-8")
        return output_path

    def load_lock(self, lock_dir: Path, lock_name: str) -> dict[str, Any]:
        """lock.yaml を PyYAML で読み込む。存在しない場合は空 dict を返す。"""
        lock_path = lock_dir / lock_name
        if not lock_path.exists():
            return {}
        return yaml.safe_load(lock_path.read_text(encoding="utf-8")) or {}

    def get_max_mtime(self, lock_dir: Path) -> str:
        """lock_dir 内入力 lock.yaml の最大 mtime を返す（共通実装へ委譲）。"""
        return get_max_mtime(lock_dir)
